"""Agent state definitions for LangGraph multi-agent workflow."""

from enum import StrEnum
from typing import Any, TypedDict


class StepType(StrEnum):
    """Categorization of agent execution steps."""

    THINK = "THINK"
    ACT = "ACT"
    OBSERVE = "OBSERVE"
    DONE = "DONE"
    ERROR = "ERROR"


class AgentName(StrEnum):
    """Core specialized agent personas in the multi-agent system."""

    COORDINATOR = "coordinator"
    EXTRACTION = "extraction"
    ANALYTICS = "analytics"


class AgentStep(TypedDict):
    """Structured representation of an agent step event."""

    agent_name: str
    step_type: str
    content: dict[str, Any]
    sequence_no: int


class ResearchPlan(TypedDict, total=False):
    """Structured plan generated by the Coordinator agent."""

    query_intent: str
    target_sectors: list[str]
    time_period: str
    required_metrics: list[str]
    planned_datasets: list[dict[str, Any]]
    sources: list[str]
    topics: list[str]
    date_range: tuple[str, str] | list[str]
    time_filter: str
    recommended_chart: str
    shrink_instructions: dict[str, Any]
    sub_tasks: list[str]


class AgentState(TypedDict):
    """Shared state dictionary tracked and updated across LangGraph agent nodes."""

    analysis_id: str
    query: str
    research_plan: ResearchPlan | None
    selected_datasets: list[dict]
    raw_data: dict[str, Any]
    statistical_results: dict[str, Any]
    insights: list[str]
    citations: list[dict]
    agent_logs: list[dict]
    current_agent: str
    extraction_errors: list[str]
    final_report: dict[str, Any] | None
    status: str


def create_initial_state(analysis_id: str, query: str) -> AgentState:
    """Create a fully initialized AgentState with default values."""
    return {
        "analysis_id": analysis_id,
        "query": query,
        "research_plan": None,
        "selected_datasets": [],
        "raw_data": {},
        "statistical_results": {},
        "insights": [],
        "citations": [],
        "agent_logs": [],
        "current_agent": "",
        "extraction_errors": [],
        "final_report": None,
        "status": "pending",
    }
